"""Vocabulary builder: look up words with the local AI, save them, revise them."""

import random

import streamlit as st

from core.llm_client import LLMError
from core.speech_synthesis import SpeechSynthesisError
from core.vocabulary_helper import VocabularyLookupError, lookup_word
from database import repository
from ui import components, state

st.title("Vocabulary")
settings = state.get_settings()
profile = state.get_profile()
ss = st.session_state

tab_add, tab_list, tab_review = st.tabs(["Look up & save", "My words", "Revision"])

# ------------------------------------------------------------------ look up
with tab_add:
    with st.form("lookup"):
        word = st.text_input("Word or short phrase", max_chars=60, placeholder="e.g. meanwhile, figure out")
        submitted = st.form_submit_button("Look up", type="primary", icon=":material/search:")
    if submitted:
        try:
            with st.spinner("Asking the local AI..."):
                ss["vocab_entry"] = lookup_word(state.get_llm(settings), word, profile["variety"],
                                                profile["proficiency"]).to_dict()
        except ValueError as exc:  # invalid input
            st.warning(str(exc))
        except (VocabularyLookupError, LLMError) as exc:
            st.error(str(exc))
    entry = ss.get("vocab_entry")
    if entry:
        with st.container(border=True):
            st.markdown(f"### {entry['word']}  <span class='la-pill'>{entry['register'] or 'neutral'}</span>",
                        unsafe_allow_html=True)
            st.markdown(f"**Meaning:** {entry['definition']}")
            if entry["example"]:
                st.markdown(f"**Example:** _{entry['example']}_")
            if entry["synonyms"]:
                st.markdown(f"**Synonyms:** {', '.join(entry['synonyms'])}")
            if entry["collocations"]:
                st.markdown(f"**Common combinations:** {', '.join(entry['collocations'])}")
            if entry["usage"]:
                st.markdown(f"**Usage:** {entry['usage']}")
            if entry["practice_question"]:
                st.markdown(f"**Practice:** {entry['practice_question']}")
            st.caption("Generated by the local AI model - double-check unusual meanings in a dictionary.")
            if st.button("Save to my words", icon=":material/bookmark_add:"):
                repository.save_word(entry, source="lookup")
                ss["vocab_entry"] = None
                st.toast(f"Saved '{entry['word']}'.")
                st.rerun()

# ------------------------------------------------------------------- list
with tab_list:
    words = repository.list_words()
    if not words:
        components.empty_state("No saved words yet. Look up a word and press 'Save to my words'.")
    else:
        show = st.radio("Show", ["Learning", "Mastered", "All"], horizontal=True)
        filtered = [w for w in words if show == "All" or (show == "Mastered") == bool(w["mastered"])]
        st.caption(f"{len(filtered)} word(s)")
        for w in filtered:
            label = f"{'✓ ' if w['mastered'] else ''}{w['word']} — {w['definition'][:70]}"
            with st.expander(label):
                if w["example"]:
                    st.markdown(f"_{w['example']}_")
                if w["synonyms"]:
                    st.caption("Synonyms: " + ", ".join(w["synonyms"]))
                notes = st.text_area("My notes", value=w["notes"], key=f"notes_{w['id']}", max_chars=2000)
                c1, c2, c3, c4 = st.columns(4)
                if c1.button("Save notes", key=f"sn_{w['id']}"):
                    repository.update_word(w["id"], notes=notes)
                    st.toast("Notes saved.")
                if c2.button("Mark learning" if w["mastered"] else "Mark mastered", key=f"m_{w['id']}"):
                    repository.update_word(w["id"], mastered=not w["mastered"])
                    st.rerun()
                if c3.button("Hear it", key=f"h_{w['id']}", icon=":material/volume_up:"):
                    try:
                        wav, _ = state.get_synthesizer(settings).synthesize(
                            f"{w['word']}. {w['example']}" if w["example"] else w["word"])
                        st.audio(wav, format="audio/wav", autoplay=True)
                    except SpeechSynthesisError as exc:
                        st.warning(f"Voice unavailable: {exc}")
                if c4.button("Delete", key=f"d_{w['id']}", icon=":material/delete:"):
                    repository.delete_word(w["id"])
                    st.rerun()
                st.caption(f"Reviewed {w['review_count']} time(s), correct {w['correct_count']}.")

# ----------------------------------------------------------------- review
with tab_review:
    pool = repository.list_words(only_unmastered=True)
    if len(pool) < 1:
        components.empty_state("Save at least one word you are still learning to start revision.")
    else:
        if "review_word" not in ss or ss["review_word"] not in [w["id"] for w in pool]:
            ss["review_word"] = random.choice(pool)["id"]
            ss["review_answered"] = None
        current = next(w for w in pool if w["id"] == ss["review_word"])
        st.markdown("**Which word matches this meaning?**")
        st.markdown(f"> {current['definition']}")
        if current["example"]:
            hint = current["example"].replace(current["word"], "_____")
            hint = hint.replace(current["word"].capitalize(), "_____")
            with st.expander("Hint: example sentence"):
                st.markdown(f"_{hint}_")
        with st.form("review_form", clear_on_submit=True):
            answer = st.text_input("Your answer", max_chars=60)
            if st.form_submit_button("Check"):
                correct = answer.strip().lower() == current["word"].lower()
                repository.record_review(current["id"], correct)
                ss["review_answered"] = (correct, answer)
        if ss.get("review_answered"):
            correct, answer = ss["review_answered"]
            if correct:
                st.success(f"Correct! **{current['word']}**")
            else:
                st.error(f"Not quite. The answer is **{current['word']}**.")
            if current["practice_question"]:
                st.markdown(f"**Use it:** {current['practice_question']} _(answer aloud in Voice Practice)_")
            if st.button("Next word", icon=":material/skip_next:"):
                others = [w for w in pool if w["id"] != current["id"]] or pool
                ss["review_word"] = random.choice(others)["id"]
                ss["review_answered"] = None
                st.rerun()
